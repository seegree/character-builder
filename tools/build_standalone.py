#!/usr/bin/env python3
"""
build_standalone.py — inlines the dev-mode module graph (tools/parts_data/*,
tools/character_gen.jsx, tools/rigger.jsx) into CharacterBuilder.jsx so the
shipped panel has zero runtime dependency on the dev repo path. This is the
"shipping build" flagged as a DEV NOTE in CharacterBuilder.jsx since the
panel was first split into modules.

Usage:  python3 tools/build_standalone.py
Reads:  CharacterBuilder.jsx, tools/character_gen.jsx, tools/rigger.jsx,
        tools/parts_data/*.jsx
Writes: dist/CharacterBuilder.jsx  (copy this one file into
        <AE>/Scripts/ScriptUI Panels/ — nothing else needs to travel with it)
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA_DIR = os.path.join(ROOT, "tools", "parts_data")
OUT_DIR = os.path.join(ROOT, "dist")

DATA_FILES = ["eyes", "brows", "mouths", "noses", "ears", "glasses",
              "facial_hair", "accessories", "shoes", "heads", "hair",
              "bodies", "tops", "bottoms", "palettes", "finish", "skeleton"]


def read(path):
    return open(path, encoding="utf-8").read()


def inline_data():
    parts = []
    for name in DATA_FILES:
        path = os.path.join(DATA_DIR, name + ".jsx")
        parts.append(read(path).strip())
    return "\n".join(parts)


def strip_data_load_block(gen_src):
    """Remove character_gen.jsx's own $.evalFile(DATA + ...) block — the
    data it loads is inlined immediately above it in the standalone build,
    in the same top-level scope, so those evalFile calls would just be
    redundant (and reference paths that don't exist next to the shipped
    panel)."""
    start = gen_src.index("// ---------- load compiled part data ----------")
    end = gen_src.index("// ---------- primitives ----------")
    return gen_src[:start] + gen_src[end:]


def strip_module_load_block(panel_src):
    """Replace CharacterBuilder.jsx's ./tools evalFile block with just the
    CB_NOAUTO flag + the CGEN/CBRIG existence check — the modules themselves
    get inlined directly above this point in the standalone build."""
    start = panel_src.index("// ---------- load modules ----------")
    end_marker = 'if(!CGEN || !CBRIG){ alert("Character Builder: could not load generator/rigger from\\n"+TD); return; }'
    end = panel_src.index(end_marker) + len(end_marker)
    replacement = (
        '$.global.CB_NOAUTO=true;\n'
        '    /*__CB_INLINED_MODULES__*/\n'
        '    var CGEN=$.global.CGEN, CBRIG=$.global.CBRIG;\n'
        '    if(!CGEN || !CBRIG){ alert("Character Builder: could not load generator/rigger (standalone build)."); return; }'
    )
    return panel_src[:start] + replacement + panel_src[end:]


def main():
    os.makedirs(OUT_DIR, exist_ok=True)

    data_src = inline_data()
    gen_src = strip_data_load_block(read(os.path.join(ROOT, "tools", "character_gen.jsx")))
    rig_src = read(os.path.join(ROOT, "tools", "rigger.jsx"))
    panel_src = strip_module_load_block(read(os.path.join(ROOT, "CharacterBuilder.jsx")))

    modules = "\n\n".join([
        "// ===== inlined: tools/parts_data/*.jsx =====",
        data_src,
        "// ===== inlined: tools/character_gen.jsx =====",
        gen_src.strip(),
        "// ===== inlined: tools/rigger.jsx =====",
        rig_src.strip(),
    ])

    header = (
        "/*\n"
        " * CharacterBuilder.jsx — STANDALONE BUILD.\n"
        " * Generated by tools/build_standalone.py — do not hand-edit.\n"
        " * Source of truth: CharacterBuilder.jsx (dev) + tools/character_gen.jsx\n"
        " * + tools/rigger.jsx + tools/parts_data/*.jsx. Edit those, then\n"
        " * `python3 tools/build_standalone.py`, then copy this file to\n"
        " * <AE>/Scripts/ScriptUI Panels/CharacterBuilder.jsx.\n"
        " * ES3 / ExtendScript.\n"
        " */\n"
    )

    out = panel_src.replace("/*__CB_INLINED_MODULES__*/", modules)
    out = header + out

    out_path = os.path.join(OUT_DIR, "CharacterBuilder.jsx")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(out)
    print("wrote", out_path, "(%d bytes)" % os.path.getsize(out_path))


if __name__ == "__main__":
    main()
